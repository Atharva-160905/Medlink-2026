import React from 'react'
import {
  UserCheck,
  Activity,
  CheckCircle2,
  Brain,
  HelpCircle,
  FileText,
  AlertCircle
} from 'lucide-react'

/**
 * Format inline markdown text: converts **bold** and *italic* cleanly.
 */
function formatInlineText(text) {
  if (!text) return null

  // Split by bold (**text**)
  const parts = text.split(/(\*\*[^*]+?\*\*)/g)
  return parts.map((part, index) => {
    if (part.startsWith('**') && part.endsWith('**')) {
      const boldText = part.slice(2, -2)
      return (
        <strong key={index} className="font-semibold text-slate-900">
          {boldText}
        </strong>
      )
    }
    // Check for *italic*
    const italicParts = part.split(/(\*[^*]+?\*)/g)
    return italicParts.map((subPart, subIndex) => {
      if (subPart.startsWith('*') && subPart.endsWith('*')) {
        return (
          <em key={`${index}-${subIndex}`} className="text-slate-600 not-italic font-medium">
            {subPart.slice(1, -1)}
          </em>
        )
      }
      return subPart
    })
  })
}

/**
 * Render status badges like [Status: High], [Status: Low], [Normal], etc.
 */
function renderStatusPill(text) {
  if (!text) return null
  const statusMatch = text.match(/(?:status:?\s*|\[status:?\s*|\[)(high|low|borderline|elevated|critical|normal)/i)
  const status = statusMatch ? statusMatch[1].toUpperCase() : null

  if (status === 'HIGH' || status === 'ELEVATED' || status === 'CRITICAL' || (!status && /\b(high|elevated|critical)\b/i.test(text) && !/\b(normal)\b/i.test(text))) {
    return (
      <span className="inline-flex items-center px-2.5 py-0.5 rounded-full text-[10px] font-bold uppercase tracking-wider bg-red-50 text-red-700 border border-red-200 flex-shrink-0">
        High
      </span>
    )
  }
  if (status === 'LOW' || status === 'DEFICIENT' || (!status && /\b(low|deficient)\b/i.test(text) && !/\b(normal)\b/i.test(text))) {
    return (
      <span className="inline-flex items-center px-2.5 py-0.5 rounded-full text-[10px] font-bold uppercase tracking-wider bg-amber-50 text-amber-700 border border-amber-200 flex-shrink-0">
        Low
      </span>
    )
  }
  if (status === 'BORDERLINE' || (!status && /\bborderline\b/i.test(text))) {
    return (
      <span className="inline-flex items-center px-2.5 py-0.5 rounded-full text-[10px] font-bold uppercase tracking-wider bg-indigo-50 text-indigo-700 border border-indigo-200 flex-shrink-0">
        Borderline
      </span>
    )
  }
  if (status === 'NORMAL') {
    return (
      <span className="inline-flex items-center px-2.5 py-0.5 rounded-full text-[10px] font-bold uppercase tracking-wider bg-emerald-50 text-emerald-700 border border-emerald-200 flex-shrink-0">
        Normal
      </span>
    )
  }
  return null
}

/**
 * Clean redundant status text from item description
 */
function cleanFindingText(finding) {
  return finding
    .replace(/\s*-\s*\[?status:?\s*(high|low|borderline|elevated|critical|normal)\]?/i, '')
    .trim()
}

/**
 * Parses raw Gemini summary text into structured clinical sections.
 */
function parseMedicalSummary(rawText) {
  if (!rawText) return []

  // 1. Normalize line breaks and remove AI preamble / rules / trailing disclaimers
  const normalized = rawText.replace(/\r\n/g, '\n')
  const cleanedText = normalized
    .replace(/^.*?(summary of your medical report|here is a summary|explained in simple terms).*?(\n|$)/im, '')
    .replace(/^---+$/gm, '')
    .replace(/^\*\*\*+$/gm, '')
    .replace(/⚠️?\s*\*?this summary is generated by ai.*$/is, '')
    .trim()

  const lines = cleanedText.split('\n')
  const sections = []
  let currentSection = null

  const isHeading = (line) => {
    const trimmed = line.trim()
    // Matches ### **Heading**, ## Heading, or **Section Name**
    if (trimmed.startsWith('#') || (trimmed.startsWith('**') && trimmed.endsWith('**') && trimmed.length < 80)) {
      return true
    }
    const lower = trimmed.toLowerCase()
    if (
      lower.startsWith('patient & test') ||
      lower.startsWith('key findings') ||
      lower.startsWith('normal findings') ||
      lower.startsWith('what this means') ||
      lower.startsWith('next steps') ||
      lower.startsWith('questions for your doctor')
    ) {
      return true
    }
    return false
  }

  const cleanHeadingTitle = (line) => {
    return line
      .replace(/^#+\s*/, '')
      .replace(/\*\*/g, '')
      .replace(/:$/, '')
      .replace(/^\d+[\.\)]\s*/, '')
      .trim()
  }

  for (let line of lines) {
    const trimmed = line.trim()
    if (!trimmed) continue

    if (isHeading(trimmed)) {
      if (currentSection) {
        sections.push(currentSection)
      }
      currentSection = {
        title: cleanHeadingTitle(trimmed),
        items: [],
        paragraphs: []
      }
    } else {
      if (!currentSection) {
        currentSection = {
          title: 'General Overview',
          items: [],
          paragraphs: []
        }
      }

      // Check if line is a bullet item (* or - or • or 1.)
      if (/^(\*|\-|•|\d+[\.\)])\s+/.test(trimmed)) {
        const itemContent = trimmed.replace(/^(\*|\-|•|\d+[\.\)])\s+/, '').trim()
        currentSection.items.push(itemContent)
      } else {
        currentSection.paragraphs.push(trimmed)
      }
    }
  }

  if (currentSection) {
    sections.push(currentSection)
  }

  return sections
}

/**
 * MedicalReportSummary Component
 * Renders structured clinical cards with bold headings, numbered tags,
 * and high/low alert badges.
 */
export default function MedicalReportSummary({ summary }) {
  if (!summary) {
    return (
      <div className="text-center py-8 text-slate-400">
        <p className="text-sm">No medical report summary available.</p>
      </div>
    )
  }

  const sections = parseMedicalSummary(summary)

  const getSectionIcon = (title) => {
    const lower = title.toLowerCase()
    if (lower.includes('patient') || lower.includes('overview')) return UserCheck
    if (lower.includes('key finding') || lower.includes('abnormal')) return Activity
    if (lower.includes('normal')) return CheckCircle2
    if (lower.includes('means') || lower.includes('understanding')) return Brain
    if (lower.includes('next steps') || lower.includes('question') || lower.includes('doctor')) return HelpCircle
    return FileText
  }

  return (
    <div className="space-y-4">
      {sections.map((section, index) => {
        const Icon = getSectionIcon(section.title)
        const sectionNumber = String(index + 1).padStart(2, '0')
        const lowerTitle = section.title.toLowerCase()
        const isOverview = lowerTitle.includes('patient') || lowerTitle.includes('overview')
        const isQuestions = lowerTitle.includes('question') || lowerTitle.includes('next step')
        const isKeyFindings = lowerTitle.includes('key finding') || lowerTitle.includes('abnormal')
        const isNormal = lowerTitle.includes('normal finding')

        return (
          <div
            key={index}
            className={`border rounded-2xl p-5 shadow-xs transition-all ${
              isNormal
                ? 'bg-emerald-50/30 border-emerald-200/80'
                : 'bg-white border-slate-200/90'
            }`}
          >
            {/* Numbered Section Header with Bold Title */}
            <div className="flex items-center gap-3 pb-3.5 mb-3.5 border-b border-slate-100">
              <span className="w-7 h-7 rounded-lg bg-slate-900 text-white font-mono text-xs font-bold flex items-center justify-center flex-shrink-0">
                {sectionNumber}
              </span>

              <div className="flex items-center gap-2">
                <Icon
                  className={`h-4 w-4 ${
                    isNormal ? 'text-emerald-700' : 'text-slate-700'
                  }`}
                />
                <h3 className="text-sm sm:text-base font-bold text-slate-900 tracking-tight">
                  {section.title}
                </h3>
              </div>
            </div>

            {/* Overview Key-Value Cards */}
            {isOverview && section.items.length > 0 && (
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-2.5">
                {section.items.map((item, itemIdx) => {
                  const colonIdx = item.indexOf(':')
                  if (colonIdx > -1) {
                    const key = item.substring(0, colonIdx).replace(/\*\*/g, '').trim()
                    const val = item.substring(colonIdx + 1).replace(/\*\*/g, '').trim()
                    return (
                      <div
                        key={itemIdx}
                        className="p-3 bg-slate-50/80 border border-slate-200/80 rounded-xl"
                      >
                        <span className="text-[10px] font-bold uppercase tracking-wider text-slate-400 block mb-0.5">
                          {key}
                        </span>
                        <span className="text-xs sm:text-sm font-semibold text-slate-900 leading-snug block">
                          {val}
                        </span>
                      </div>
                    )
                  }
                  return (
                    <div
                      key={itemIdx}
                      className="p-3 bg-slate-50/80 border border-slate-200/80 rounded-xl text-xs sm:text-sm text-slate-800"
                    >
                      {formatInlineText(item)}
                    </div>
                  )
                })}
              </div>
            )}

            {/* Key Findings List with Status Badges */}
            {isKeyFindings && section.items.length > 0 && (
              <div className="space-y-2.5">
                {section.items.map((finding, fIdx) => {
                  const statusPill = renderStatusPill(finding)
                  const cleaned = cleanFindingText(finding)

                  // Check if there is an explanation part separated by '-'
                  const parts = cleaned.split(/\s+-\s+/)
                  const titlePart = parts[0]
                  const explanationPart = parts.slice(1).join(' - ')

                  return (
                    <div
                      key={fIdx}
                      className="p-3.5 bg-slate-50 border border-slate-200/80 rounded-xl flex flex-col gap-1.5"
                    >
                      <div className="flex items-start justify-between gap-3">
                        <div className="text-xs sm:text-sm font-semibold text-slate-900 leading-snug">
                          {formatInlineText(titlePart)}
                        </div>
                        {statusPill}
                      </div>

                      {explanationPart && (
                        <p className="text-xs text-slate-600 leading-relaxed pt-0.5">
                          {formatInlineText(explanationPart)}
                        </p>
                      )}
                    </div>
                  )
                })}
              </div>
            )}

            {/* Questions for Your Doctor */}
            {isQuestions && section.items.length > 0 && (
              <div className="space-y-2.5">
                {section.items.map((q, qIdx) => (
                  <div
                    key={qIdx}
                    className="p-3.5 bg-slate-50/90 hover:bg-slate-100/80 border border-slate-200/90 rounded-xl flex items-start gap-3 transition-colors"
                  >
                    <span className="px-2 py-0.5 rounded-md text-[10px] font-mono font-bold bg-slate-900 text-white flex-shrink-0 mt-0.5">
                      Q{qIdx + 1}
                    </span>
                    <p className="text-xs sm:text-sm font-medium text-slate-800 leading-relaxed">
                      {formatInlineText(q)}
                    </p>
                  </div>
                ))}
              </div>
            )}

            {/* Standard Bullet List (if not overview, findings, or questions) */}
            {!isOverview && !isQuestions && !isKeyFindings && section.items.length > 0 && (
              <ul className="space-y-2">
                {section.items.map((item, i) => (
                  <li
                    key={i}
                    className="flex items-start gap-2.5 text-xs sm:text-sm text-slate-700 leading-relaxed"
                  >
                    <span className="w-1.5 h-1.5 rounded-full bg-slate-400 mt-2 flex-shrink-0" />
                    <div>{formatInlineText(item)}</div>
                  </li>
                ))}
              </ul>
            )}

            {/* Narrative / Paragraph Text */}
            {section.paragraphs.length > 0 && (
              <div className="space-y-2 mt-2 first:mt-0">
                {section.paragraphs.map((p, pIdx) => (
                  <p key={pIdx} className="text-xs sm:text-sm text-slate-700 leading-relaxed">
                    {formatInlineText(p)}
                  </p>
                ))}
              </div>
            )}
          </div>
        )
      })}
    </div>
  )
}
